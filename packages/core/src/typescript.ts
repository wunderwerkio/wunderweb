// Model → TypeScript types (component props, component map keys).

import { type Expr, parseExpr } from "./expr.js";
import {
	breakpoints,
	enumValues,
	type Field,
	type Model,
	type TypeSpec,
} from "./model.js";

// Token types, widened to string with `open` (runtime code for any theme).
const TOKENS = ["Color", "ButtonVariant", "ContainerSize", "Breakpoint"];

export interface TsOptions {
	/** Token types as string and Responsive as a string-keyed map. */
	open?: boolean;
}

export function toTypeScript(model: Model, opts: TsOptions = {}): string {
	const e = new TsEmitter(model, opts.open ?? false);
	const bps = breakpoints(model);
	const responsive = opts.open
		? "{ [breakpoint: string]: T | undefined }"
		: `{ ${bps.map((b) => `${JSON.stringify(b)}?: T`).join("; ")} }`;
	const project = Object.values(model.blocks)
		.filter((b) => b.kind === "project")
		.map((b) => b.name);

	return [
		`// Generated by wunderweb from core v${model.version} + theme + blocks - do not edit.`,
		"",
		"/** Per-breakpoint value, mobile first. */",
		`export type Responsive<T> = ${responsive};`,
		"",
		"// Types",
		...Object.entries(model.types).map(([n, s]) => `${e.type(n, s)}\n`),
		"// Roles (what may go where)",
		...Object.keys(model.roles).map((n) => `${e.role(n)}\n`),
		"// Traits (shared block fields)",
		...Object.entries(model.traits).map(
			([n, f]) => `export interface ${n} {\n${e.fields(f)}\n}\n`,
		),
		"// Blocks",
		...Object.keys(model.blocks).map((n) => `${e.block(n)}\n`),
		"// Project blocks: one component each (generated component map)",
		`export interface BlockMap {\n${project
			.map((n) => `  ${n}: ${n}Block;`)
			.join("\n")}\n}`,
		"",
		"export type BlockType = keyof BlockMap;",
		"export type AnyBlock = BlockMap[BlockType];",
		`export type LayoutDocument = ${model.roots.join(" | ")};`,
		"",
	].join("\n");
}

class TsEmitter {
	constructor(
		private readonly model: Model,
		private readonly open: boolean,
	) {}

	name(n: string): string {
		return this.model.blocks[n] ? `${n}Block` : n;
	}

	expr(expr: Expr): string {
		if ("list" in expr) {
			const inner = this.expr(expr.list);
			return "union" in expr.list ? `(${inner})[]` : `${inner}[]`;
		}
		if ("generic" in expr) {
			return `${expr.generic}<${this.expr(expr.arg)}>`;
		}
		if ("union" in expr) {
			return expr.union.map((x) => this.expr(x)).join(" | ");
		}
		if (expr.name === "integer") {
			return "number";
		}
		return ["string", "number", "boolean"].includes(expr.name)
			? expr.name
			: this.name(expr.name);
	}

	fields(fields: Field[]): string {
		return fields
			.map((f) => {
				const doc = tsDoc(
					[
						f.deprecated ? `@deprecated ${f.doc ?? ""}`.trim() : f.doc,
						f.default !== undefined
							? `@default ${JSON.stringify(f.default)}`
							: undefined,
					],
					"  ",
				);
				return `${doc}  ${f.name}${f.optional ? "?" : ""}: ${this.expr(f.expr)};`;
			})
			.join("\n");
	}

	/** Role: union of its members (roles by name, blocks as <Name>Block). */
	role(name: string): string {
		const spec = this.model.roles[name];
		const members = (spec?.members ?? []).map((m) => this.name(m));
		const doc = tsDoc([spec?.doc, "Role."]);
		return `${doc}export type ${name} = ${members.length ? members.join(" | ") : "never"};`;
	}

	type(name: string, spec: string | TypeSpec): string {
		if (typeof spec === "string") {
			return `export type ${name} = ${this.expr(parseExpr(spec, () => {}))};`;
		}

		const doc = tsDoc([spec.doc]);
		if (spec.enum && this.open && TOKENS.includes(name)) {
			return `${doc}export type ${name} = string;`;
		}
		if (spec.enum) {
			const values = enumValues(spec);
			return `${doc}export type ${name} = ${values.length ? values.map((v) => JSON.stringify(v)).join(" | ") : "never"};`;
		}
		if (spec.fields) {
			const fields = Object.entries(spec.fields).map(([key, fs]) => {
				const long = typeof fs === "object";
				const f: Field = {
					name: key.replace(/\?$/, ""),
					optional: key.endsWith("?"),
					expr: parseExpr(long ? fs.type : fs, () => {}),
				};
				if (long && fs.doc) {
					f.doc = fs.doc;
				}
				if (long && fs.deprecated === true) {
					f.deprecated = true;
				}
				if (long && fs.default !== undefined) {
					f.default = fs.default;
				}
				return f;
			});
			return `${doc}export interface ${name} {\n${this.fields(fields)}\n}`;
		}

		const range = [
			spec.pattern && `pattern ${spec.pattern}`,
			spec.min !== undefined && `min ${spec.min}`,
			spec.max !== undefined && `max ${spec.max}`,
		].filter((x): x is string => Boolean(x));
		return `${tsDoc([spec.doc, range.join(", ")])}export type ${name} = ${spec.type === "integer" ? "number" : spec.type};`;
	}

	block(name: string): string {
		const b = this.model.blocks[name];
		if (!b) {
			return "";
		}
		const traitFields = new Set(
			b.traits.flatMap((t) => (this.model.traits[t] ?? []).map((f) => f.name)),
		);
		const own = b.fields.filter((f) => !traitFields.has(f.name));
		const traitDefaults = b.fields.filter(
			(f) => traitFields.has(f.name) && f.default !== undefined,
		);
		const defaultsDoc = traitDefaults.map(
			(f) => `@defaultOverride ${f.name} ${JSON.stringify(f.default)}`,
		);

		const ext = b.traits.length ? ` extends ${b.traits.join(", ")}` : "";
		// No `id`: block ids are editor metadata the loader keeps from components.
		const body = [`  type: "${name}";`, this.fields(own)]
			.filter(Boolean)
			.join("\n");
		const roles = b.roles.length ? `Roles: ${b.roles.join(", ")}.` : undefined;
		return `${tsDoc([b.doc, roles, ...defaultsDoc])}export interface ${name}Block${ext} {\n${body}\n}`;
	}
}

function tsDoc(lines: (string | undefined)[], indent = ""): string {
	const clean = lines
		.filter((l): l is string => Boolean(l))
		.map((l) => l.replaceAll("*/", "*\\/"));
	if (!clean.length) {
		return "";
	}
	if (clean.length === 1) {
		return `${indent}/** ${clean[0]} */\n`;
	}
	return `${indent}/**\n${clean.map((l) => `${indent} * ${l}`).join("\n")}\n${indent} */\n`;
}
