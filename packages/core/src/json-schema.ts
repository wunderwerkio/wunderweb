// Model → JSON Schema 2020-12 (content validation, editor autocomplete).
// Custom keywords: x-kind (block origin: core | project), x-roles (roles a
// block joins), x-rules (declarative block rules), x-role (role rank on role
// unions), x-traits, x-richText (vocabulary), x-tokens (theme token values),
// x-values (enum map values).

import { Ajv2020, type ErrorObject } from "./ajv.js";
import { BLOCK_ID_PATTERN } from "./block-ids.js";
import { type Expr, parseExpr } from "./expr.js";
import {
	BUILTINS,
	breakpoints,
	enumValues,
	type Field,
	type Model,
	roleBlocks,
	SchemaError,
	type TypeSpec,
} from "./model.js";

export type JsonSchema = Record<string, unknown>;

const DEF = (name: string) => `#/$defs/${name}`;

/** Accepts no value: an empty role or block union. */
const NOTHING: JsonSchema = { not: {} };

export function toJsonSchema(model: Model, name: string): JsonSchema {
	const errors: string[] = [];
	const emit = new Emitter(model, errors);

	const defs: Record<string, JsonSchema> = {};
	for (const [n, spec] of Object.entries(model.types)) {
		defs[n] = emit.type(n, spec);
	}
	for (const [rank, n] of Object.keys(model.roles).entries()) {
		defs[n] = emit.role(n, rank);
	}
	for (const n of Object.keys(model.blocks)) {
		defs[n] = emit.block(n);
	}

	checkDefaults(model, defs, emit, errors);
	if (errors.length) {
		throw new SchemaError([...new Set(errors)]);
	}

	return {
		$schema: "https://json-schema.org/draft/2020-12/schema",
		$id: `urn:wunderweb:${name}:v${model.version}`,
		title: "wunderweb document",
		description: `Roots: ${model.roots.join(", ")}. Generated by wunderweb from core v${model.version} + theme + blocks - do not edit.`,
		"x-version": model.version,
		"x-richText": model.richText,
		"x-tokens": model.tokens,
		oneOf: model.roots.map((r) => ({ $ref: DEF(r) })),
		$defs: defs,
	};
}

class Emitter {
	constructor(
		private readonly model: Model,
		private readonly errors: string[],
	) {}

	type(name: string, spec: string | TypeSpec): JsonSchema {
		if (typeof spec === "string") {
			return this.alias(spec, name);
		}

		const base = spec.doc ? { description: spec.doc } : {};
		if (spec.enum) {
			const meta = Array.isArray(spec.enum) ? {} : { "x-values": spec.enum };
			return { ...base, enum: enumValues(spec), ...meta };
		}
		if (spec.fields) {
			// Field lists of value types are parsed by the model for blocks only.
			return { ...base, ...this.object(this.valueFields(name, spec)) };
		}

		const out: JsonSchema = { ...base, type: BUILTINS[spec.type ?? ""] };
		if (spec.pattern) {
			out.pattern = spec.pattern;
		}
		if (spec.min !== undefined) {
			out.minimum = spec.min;
		}
		if (spec.max !== undefined) {
			out.maximum = spec.max;
		}
		return out;
	}

	/** Role: union of its member blocks (member roles flattened); empty = accepts nothing. */
	role(name: string, rank: number): JsonSchema {
		const blocks = roleBlocks(this.model, name);
		const doc = this.model.roles[name]?.doc;
		const members = blocks.length ? blocks.join(", ") : "none";
		return {
			description: `${doc ? `${doc} ` : ""}Role; blocks: ${members}.`,
			"x-role": rank,
			...blockUnion(blocks),
		};
	}

	block(name: string): JsonSchema {
		const b = this.model.blocks[name];
		if (!b) {
			return {};
		}
		const header = {
			type: { const: name },
			id: {
				type: "string",
				pattern: BLOCK_ID_PATTERN,
				description:
					"Stable block id, unique within the file (editor metadata, not passed to components). `wunderweb format` fills it in.",
			},
		};
		return {
			...(b.doc ? { description: b.doc } : {}),
			"x-kind": b.kind,
			"x-roles": b.roles,
			...(b.traits.length ? { "x-traits": b.traits } : {}),
			...(b.rules.length ? { "x-rules": b.rules } : {}),
			...this.object(b.fields, header, ["type"]),
		};
	}

	expr(expr: Expr): JsonSchema {
		if ("list" in expr) {
			return { type: "array", items: this.expr(expr.list) };
		}
		if ("generic" in expr) {
			return {
				type: "object",
				"x-responsive": true,
				properties: Object.fromEntries(
					breakpoints(this.model).map((bp) => [bp, this.expr(expr.arg)]),
				),
				additionalProperties: false,
				minProperties: 1,
			};
		}
		if ("union" in expr) {
			const set = this.blockSet(expr);
			if (set) {
				return blockUnion(set);
			}
			if (expr.union.some((e) => this.blockSet(e))) {
				this.errors.push(
					`union mixes blocks and values: ${JSON.stringify(expr)}`,
				);
			}
			return { anyOf: expr.union.map((e) => this.expr(e)) };
		}

		const builtin = BUILTINS[expr.name];
		if (builtin) {
			return { type: builtin };
		}
		return { $ref: DEF(expr.name) };
	}

	field(f: Field): JsonSchema {
		const s: JsonSchema = { ...this.expr(f.expr) };
		if (f.doc) {
			s.description = f.doc;
		}
		if (f.default !== undefined) {
			s.default = f.default;
		}
		// Annotation (JSON Schema 2020-12): editors strike it through, lint warns.
		if (f.deprecated) {
			s.deprecated = true;
		}
		// Required fields must be non-empty; minLength / minItems act only on strings / arrays.
		if (!f.optional) {
			s.minLength = 1;
			s.minItems = 1;
		}
		return s;
	}

	/**
	 * Block names an expression stands for (roles and aliases flattened), or
	 * null if it is not blocks-only. An empty role gives [].
	 */
	blockSet(expr: Expr, seen = new Set<string>()): string[] | null {
		if ("union" in expr) {
			const sets = expr.union.map((e) => this.blockSet(e, seen));
			return sets.includes(null) ? null : (sets as string[][]).flat();
		}
		if (!("name" in expr)) {
			return null;
		}
		if (this.model.blocks[expr.name]) {
			return [expr.name];
		}
		if (this.model.roles[expr.name]) {
			return roleBlocks(this.model, expr.name);
		}

		const alias = this.model.types[expr.name];
		if (typeof alias !== "string" || seen.has(expr.name)) {
			return null;
		}
		seen.add(expr.name);
		return this.blockSet(this.parse(alias, expr.name), seen);
	}

	parse(text: string, where: string): Expr {
		return parseExpr(text, (m) => this.errors.push(`${where}: ${m}`));
	}

	private alias(text: string, name: string): JsonSchema {
		const expr = this.parse(text, name);
		const set = this.blockSet(expr);
		return set
			? {
					description: `One of: ${set.length ? set.join(", ") : "none"}`,
					...blockUnion(set),
				}
			: this.expr(expr);
	}

	private valueFields(name: string, spec: TypeSpec): Field[] {
		return Object.entries(spec.fields ?? {}).map(([key, fs]) => {
			const optional = key.endsWith("?");
			const long = typeof fs === "object";
			const f: Field = {
				name: optional ? key.slice(0, -1) : key,
				optional,
				expr: this.parse(long ? fs.type : fs, `${name}.${key}`),
			};
			if (long && fs.default !== undefined) {
				f.default = fs.default;
			}
			if (long && fs.doc) {
				f.doc = fs.doc;
			}
			if (long && fs.deprecated === true) {
				f.deprecated = true;
			}
			return f;
		});
	}

	private object(
		fields: Field[],
		extraProps: JsonSchema = {},
		extraRequired: string[] = [],
	): JsonSchema {
		return {
			type: "object",
			properties: {
				...extraProps,
				...Object.fromEntries(fields.map((f) => [f.name, this.field(f)])),
			},
			required: [
				...extraRequired,
				...fields.filter((f) => !f.optional).map((f) => f.name),
			],
			additionalProperties: false,
		};
	}
}

/** Block union: discriminated by `type` for precise errors; empty = accepts nothing. */
function blockUnion(names: string[]): JsonSchema {
	const unique = [...new Set(names)];
	if (!unique.length) {
		return { ...NOTHING };
	}
	return {
		type: "object",
		required: ["type"],
		discriminator: { propertyName: "type" },
		oneOf: unique.map((n) => ({ $ref: DEF(n) })),
	};
}

/** Defaults must be valid values of their field type. */
function checkDefaults(
	model: Model,
	defs: Record<string, JsonSchema>,
	emit: Emitter,
	errors: string[],
) {
	const ajv = new Ajv2020({ strict: false, discriminator: true });
	for (const b of Object.values(model.blocks)) {
		for (const f of b.fields) {
			if (f.default === undefined) {
				continue;
			}
			const validate = ajv.compile({ ...emit.expr(f.expr), $defs: defs });
			if (!validate(f.default)) {
				errors.push(
					`${b.name}.defaults.${f.name}: invalid default ${JSON.stringify(f.default)} (${(validate.errors ?? []).map(defaultError).join("; ")})`,
				);
			}
		}
	}
}

/** Names the offending field, e.g. `unknown field "bleed" at /place`. */
function defaultError(e: ErrorObject): string {
	const at = e.instancePath || "/";
	if (e.keyword === "additionalProperties") {
		return `unknown field "${String(e.params.additionalProperty)}" at ${at}`;
	}
	return `${at} ${e.message ?? e.keyword}`;
}
