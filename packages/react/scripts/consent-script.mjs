// Writes src/consent-script.min.ts: the two parts of the consent client
// script (src/consent-script.js, the readable source) minified, as the
// strings consent.tsx inlines into every page. Run after changing the
// script: node scripts/consent-script.mjs [--check]
//
// Each function is serialised on its own, so the module may hold nothing
// but the two exported functions: anything else at module level (imports,
// constants, helpers) would be missing in the page.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import { transform } from "esbuild";
import ts from "typescript";

const SRC = join(import.meta.dirname, "..", "src", "consent-script.js");
const OUT = join(import.meta.dirname, "..", "src", "consent-script.min.ts");
const PARTS = [
	["consentHead", "consentHeadSource"],
	["mountConsent", "mountConsentSource"],
];

function fail(message) {
	console.error(`scripts/consent-script.mjs: ${message}`);
	process.exit(1);
}

// Only `export function <part>(…) {…}` at module level.
const file = ts.createSourceFile(
	SRC,
	readFileSync(SRC, "utf8"),
	ts.ScriptTarget.Latest,
	true,
	ts.ScriptKind.JS,
);
const names = [];
for (const st of file.statements) {
	const exported = ts
		.getModifiers(st)
		?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
	if (!ts.isFunctionDeclaration(st) || !exported || !st.name) {
		fail(
			`src/consent-script.js line ${file.getLineAndCharacterOfPosition(st.getStart()).line + 1}: only the exported functions ${PARTS.map(([n]) => n).join(", ")} may be at module level (each is inlined on its own)`,
		);
	}
	names.push(st.name.text);
}
if (names.join() !== PARTS.map(([n]) => n).join()) {
	fail(`src/consent-script.js must export ${PARTS.map(([n]) => n).join(", ")}`);
}

const mod = await import(pathToFileURL(SRC).href);
let text =
	"// Generated by scripts/consent-script.mjs from consent-script.js (the\n" +
	"// readable source): do not edit.\n";
for (const [name, out] of PARTS) {
	// An assignment keeps the function an expression (no name needed).
	const { code } = await transform(`x=${mod[name]}`, {
		minify: true,
		target: "es2020",
		loader: "js",
		legalComments: "none",
	});
	const source = code.replace(/^x=/, "").replace(/;\n$/, "");
	if (!source.startsWith("function") || /[\t\n]/.test(source)) {
		fail(`unexpected esbuild output for ${name}: ${source.slice(0, 80)}`);
	}
	if (/<\/script|<!--/i.test(source)) {
		fail(
			`${name} contains "</script" or "<!--" (it is inlined in a script tag)`,
		);
	}
	text += `\n/** \`${name}\`, minified: \`(\${${out}})(…)\`. */\n`;
	text += `export const ${out} = ${JSON.stringify(source)};\n`;
}

if (process.argv.includes("--check")) {
	let current = "";
	try {
		current = readFileSync(OUT, "utf8");
	} catch {
		// missing: stale
	}
	if (current !== text) {
		fail("src/consent-script.min.ts is stale: node scripts/consent-script.mjs");
	}
	process.exit(0);
}
writeFileSync(OUT, text);
